"""Generate ``generated_tables.tex`` from ``results/*_metrics.json``.

Run from the repository root (or anywhere) after ``python main.py``:

    python report/make_tables.py

The LaTeX report ``\\input``s the generated file, so every number in the tables comes
straight from the experiment output.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
METHODS = ["DMD", "EDMD", "Deep Koopman"]


def sci(x: float) -> str:
    """Format ``x`` as ``a.b x 10^n`` in LaTeX math mode."""
    if x == 0:
        return "$0$"
    mant, exp = f"{x:.1e}".split("e")
    return f"${mant}\\times10^{{{int(exp)}}}$"


def capped(value: float, cap: float, fmt: str) -> str:
    """``value`` formatted, prefixed with ``\\ge`` when it hit the horizon ``cap``."""
    text = fmt.format(value)
    return f"$\\geq {text}$" if value >= cap - 1e-6 else f"${text}$"


def pendulum_table(m: dict) -> str:
    cfg = m["config"]
    period = 2 * 3.141592653589793 / (9.81 ** 0.5)
    rows = []
    for name in METHODS:
        v = m["methods"][name]
        rows.append(
            f"{name} & {v['mean_rollout_error']:.3f} & "
            f"{capped(v['median_valid_time_s'], cfg['t_final'], '{:.2f}')} & "
            f"{capped(v['median_valid_time_s'] / period, cfg['t_final'] / period, '{:.1f}')} & "
            f"{100 * v['fraction_never_exceeded']:.0f}\\% & "
            f"{sci(v['one_step_rmse'])} \\\\"
        )
    return "\n".join(rows)


def lorenz_table(m: dict) -> str:
    rows = []
    for name in METHODS:
        v = m["methods"][name]
        rows.append(
            f"{name} & {v['mean_rollout_error']:.3f} & {v['median_valid_time_lyapunov']:.2f} & "
            f"{v['mean_valid_time_lyapunov']:.2f} & {100 * v['fraction_never_exceeded']:.0f}\\% & "
            f"{sci(v['one_step_rmse'])} \\\\"
        )
    return "\n".join(rows)


def ladder_table(m: dict) -> str:
    return "\n".join(f"{k} & {v:.3f} \\\\" for k, v in m["deep_koopman_error_ladder"].items())


def main() -> None:
    pend = json.loads((ROOT / "results" / "pendulum_metrics.json").read_text())
    lor = json.loads((ROOT / "results" / "lorenz_metrics.json").read_text())
    pc, lc = pend["config"], lor["config"]
    out = [
        "% AUTO-GENERATED by report/make_tables.py -- do not edit by hand.",
        "\\newcommand{\\pendTableRows}{%\n" + pendulum_table(pend) + "\n}",
        "\\newcommand{\\lorenzTableRows}{%\n" + lorenz_table(lor) + "\n}",
        "\\newcommand{\\ladderTableRows}{%\n" + ladder_table(lor) + "\n}",
        f"\\newcommand{{\\pendNTrain}}{{{pc['n_train']}}}",
        f"\\newcommand{{\\pendNVal}}{{{pc['n_val']}}}",
        f"\\newcommand{{\\pendNTest}}{{{pc['n_test']}}}",
        f"\\newcommand{{\\pendDamping}}{{{pc['damping']:g}}}",
        f"\\newcommand{{\\pendDt}}{{{pc['dt']:g}}}",
        f"\\newcommand{{\\pendTfinal}}{{{pc['t_final']:g}}}",
        f"\\newcommand{{\\pendDKLatent}}{{{pc['dk_latent']}}}",
        f"\\newcommand{{\\pendDKHorizon}}{{{pc['dk_horizon']}}}",
        f"\\newcommand{{\\pendDKIter}}{{{pc['dk_iterations']}}}",
        f"\\newcommand{{\\pendEDMDK}}{{{pend['edmd_selected']['harmonics']}}}",
        f"\\newcommand{{\\pendEDMDP}}{{{pend['edmd_selected']['velocity_degree']}}}",
        f"\\newcommand{{\\pendEDMDFeatures}}{{{pend['edmd_selected']['n_features']}}}",
        f"\\newcommand{{\\lorNTrain}}{{{lc['n_train']}}}",
        f"\\newcommand{{\\lorNVal}}{{{lc['n_val']}}}",
        f"\\newcommand{{\\lorNTest}}{{{lc['n_test']}}}",
        f"\\newcommand{{\\lorNStarts}}{{{lc['n_test_starts']}}}",
        f"\\newcommand{{\\lorDt}}{{{lc['dt']:g}}}",
        f"\\newcommand{{\\lorDKLatent}}{{{lc['dk_latent']}}}",
        f"\\newcommand{{\\lorDKHorizon}}{{{lc['dk_horizon']}}}",
        f"\\newcommand{{\\lorDKIter}}{{{lc['dk_iterations']}}}",
        f"\\newcommand{{\\lorEDMDDegree}}{{{lor['edmd_selected']['degree']}}}",
        f"\\newcommand{{\\lorEDMDFeatures}}{{{lor['edmd_selected']['n_features']}}}",
    ]
    target = ROOT / "report" / "generated_tables.tex"
    target.write_text("\n".join(out) + "\n")
    print(f"wrote {target}")


if __name__ == "__main__":
    main()
